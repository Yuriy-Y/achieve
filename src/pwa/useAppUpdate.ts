import { useCallback, useEffect, useRef } from 'react'
import { useRegisterSW } from 'virtual:pwa-register/react'

/**
 * `localStorage` key used to remember that the user postponed an available
 * update. The flag lives outside the Data_Set (it is never exported) and is
 * read on the next cold start so a waiting worker is applied before data loads
 * (Req 10.11).
 */
export const UPDATE_POSTPONED_KEY = 'achievement-tracker.updatePostponed'

/**
 * How long the hook waits between background update checks triggered by the app
 * becoming visible. Standalone apps rarely navigate, so the browser's own update
 * check (which runs on navigation) seldom fires; checking on `visibilitychange`
 * keeps the installed app reasonably fresh (Req 10.8). Throttled to once per
 * hour so resuming the app repeatedly does not hammer the server.
 */
const UPDATE_CHECK_INTERVAL_MS = 60 * 60 * 1000

/**
 * The public surface the UI needs for the prompt-mode update flow.
 *
 * - `needRefresh` is `true` while a new App_Version has been downloaded and is
 *   waiting to be applied (Req 10.9).
 * - `apply()` activates the waiting Service_Worker and reloads into the new
 *   version (Req 10.10).
 * - `postpone()` hides the prompt without updating and records the choice so the
 *   update is applied on the next launch instead (Req 10.11).
 */
export interface AppUpdate {
  needRefresh: boolean
  apply: () => void
  postpone: () => void
}

/** Current epoch milliseconds. Isolated in a helper so the clock read stays out of render scope. */
function now(): number {
  return Date.now()
}

/** Calls `registration.update()`; a failure is swallowed so the installed version keeps running. */
function safeUpdate(registration: ServiceWorkerRegistration | undefined): void {
  if (!registration) return
  // An update check fails when the device is offline, VPN is off, or the GitLab
  // Pages session has expired and the sw.js fetch is redirected to sign-in. In
  // every case the installed worker stays active, so the rejection is ignored
  // on purpose: no message is shown and the cached version continues to run
  // (design: "catch and ignore rejected update()", Req 10.8).
  registration.update().catch(() => {
    /* ignored on purpose */
  })
}

/**
 * React hook wrapping `useRegisterSW` from `virtual:pwa-register/react` for the
 * prompt-mode update flow described in the design's PWA section.
 *
 * The Service_Worker is generated by `vite-plugin-pwa` with
 * `registerType: 'prompt'`, so a downloaded update is never applied without the
 * user's choice. This hook:
 *
 * - exposes `needRefresh` and the `apply` / `postpone` actions for `UpdatePrompt`;
 * - on registration, if a worker is already waiting and the user postponed an
 *   earlier update, clears the flag and applies immediately (one reload) before
 *   the rest of the app settles (Req 10.11);
 * - logs registration errors to the console only, so an unsupported browser
 *   still runs the app online without offline support (Req 10.5);
 * - re-checks for an update when the app becomes visible, at most once per hour,
 *   swallowing a rejected `registration.update()` (Req 10.8).
 *
 * The persisted Data_Set is never touched by the Service_Worker, so applying an
 * update keeps all Activities, Daily_Values and Goal_Versions (Req 10.12).
 */
export function useAppUpdate(): AppUpdate {
  const registrationRef = useRef<ServiceWorkerRegistration | undefined>(undefined)
  const lastCheckRef = useRef(0)

  // The update function is held in a ref so the registration callback can apply a
  // waiting worker without listing it as a dependency (it is stable in practice).
  const updateServiceWorkerRef = useRef<(reloadPage?: boolean) => Promise<void>>(() => Promise.resolve())

  // Invoked asynchronously by the Service_Worker registration, never during
  // render, so the clock read and storage access here are effects, not render work.
  const onRegisteredSW = useCallback(
    (_swScriptUrl: string, registration: ServiceWorkerRegistration | undefined): void => {
      registrationRef.current = registration
      lastCheckRef.current = now()

      // If a worker is already waiting (a previous update the user postponed) and
      // the postponed flag is set, apply it now before anything else settles.
      // Clearing the flag first prevents a reload loop if activation re-runs this
      // callback (Req 10.11).
      if (registration?.waiting && localStorage.getItem(UPDATE_POSTPONED_KEY) === '1') {
        localStorage.removeItem(UPDATE_POSTPONED_KEY)
        void updateServiceWorkerRef.current(true)
      }
    },
    [],
  )

  const onRegisterError = useCallback((error: unknown): void => {
    // Registration can fail on an unsupported browser or outside a secure
    // context. The app still works online; offline support is simply absent.
    console.error('Service worker registration failed', error)
  }, [])

  const {
    needRefresh: [needRefresh, setNeedRefresh],
    updateServiceWorker,
  } = useRegisterSW({ onRegisteredSW, onRegisterError })

  // Keep the ref in sync outside render so onRegisteredSW can apply a waiting
  // worker without taking updateServiceWorker as a dependency.
  useEffect(() => {
    updateServiceWorkerRef.current = updateServiceWorker
  }, [updateServiceWorker])

  // Standalone apps rarely navigate, so trigger a background update check when the
  // app becomes visible, throttled to once per hour.
  useEffect(() => {
    const onVisible = (): void => {
      if (document.visibilityState !== 'visible') return
      if (now() - lastCheckRef.current < UPDATE_CHECK_INTERVAL_MS) return
      lastCheckRef.current = now()
      safeUpdate(registrationRef.current)
    }
    document.addEventListener('visibilitychange', onVisible)
    return () => document.removeEventListener('visibilitychange', onVisible)
  }, [])

  const apply = useCallback(() => {
    // Tells the waiting worker to skip waiting and reloads the page into the new
    // App_Version (Req 10.10). A stale postponed flag would be pointless now.
    localStorage.removeItem(UPDATE_POSTPONED_KEY)
    void updateServiceWorker(true)
  }, [updateServiceWorker])

  const postpone = useCallback(() => {
    // Hide the prompt without updating and remember the choice so the waiting
    // worker is applied on the next cold start (Req 10.11).
    setNeedRefresh(false)
    localStorage.setItem(UPDATE_POSTPONED_KEY, '1')
  }, [setNeedRefresh])

  return { needRefresh, apply, postpone }
}
